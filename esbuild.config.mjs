import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { copyFileSync, mkdirSync, watchFile } from "fs";

const outDir = "dist";
const staticFiles = ["manifest.json", "styles.css"];

// Obsidian charge main.js, manifest.json et styles.css depuis le même dossier : on copie les deux derniers dans dist/.
const copyStatic = () => {
	mkdirSync(outDir, { recursive: true });
	for (const file of staticFiles) copyFileSync(file, `${outDir}/${file}`);
};

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins],
	// sql.js : le binaire WebAssembly de SQLite est embarqué dans main.js (aucun fichier à côté du plugin).
	loader: { ".wasm": "binary" },
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: `${outDir}/main.js`,
	plugins: [{
		name: "copy-static-files",
		setup(build) {
			build.onEnd(copyStatic);
		},
	}],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	// Re-copie manifest.json / styles.css à chaque modification (esbuild ne surveille que les fichiers importés).
	for (const file of staticFiles) watchFile(file, { interval: 300 }, copyStatic);
	await context.watch();
}